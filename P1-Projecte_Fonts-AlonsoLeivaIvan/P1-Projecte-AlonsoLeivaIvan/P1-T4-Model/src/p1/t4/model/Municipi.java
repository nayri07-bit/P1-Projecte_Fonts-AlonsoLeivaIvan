package p1.t4.model;

public class Municipi {

    private int codim;
    private String nom;
    private int codiProv;

    public Municipi() {}

    public int getCodim() {
        return codim;
    }

    public void setCodim(int codim) {
        this.codim = codim;
    }

    public String getNom() {
        return nom;
    }

    public void setNom(String nom) {
        this.nom = nom;
    }

    public int getCodiProv() {
        return codiProv;
    }

    public void setCodiProv(int codiProv) {
        this.codiProv = codiProv;
    }
}
